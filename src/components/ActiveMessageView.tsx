import React, { useState } from 'react';
import { RegulatoryResponse } from '../types/regulatory';

interface ActiveMessageViewProps {
  response: RegulatoryResponse;
  onSelectQuery?: (query: string) => void;
}

export const ActiveMessageView: React.FC<ActiveMessageViewProps> = ({
  response,
}) => {
  const [evidenceExpanded, setEvidenceExpanded] = useState<boolean>(true);
  const [highlightedSourceId, setHighlightedSourceId] = useState<string | null>(null);
  const [copyFeedback, setCopyFeedback] = useState<boolean>(false);

  const handleCitationClick = (citationNum: number) => {
    // Ensure section is open
    setEvidenceExpanded(true);
    const targetSource = response.citations.find((c) => c.citationNumber === citationNum);
    if (targetSource) {
      setHighlightedSourceId(targetSource.id);
      setTimeout(() => {
        const el = document.getElementById(targetSource.id);
        if (el) {
          el.scrollIntoView({ behavior: 'smooth', block: 'center' });
        }
      }, 50);

      setTimeout(() => {
        setHighlightedSourceId(null);
      }, 2500);
    }
  };

  const handleCopyLegalMemo = () => {
    const formattedText = `REGULENS LEGAL MEMORANDUM\n` +
      `Date: ${response.timestamp}\n` +
      `Query: ${response.userQuery}\n\n` +
      `TITLE: ${response.title}\n` +
      `${response.applicableRegime}\n\n` +
      `EXECUTIVE SYNTHESIS:\n${response.summaryParagraph}\n\n` +
      response.sections
        .map((s) => `${s.title}\n${s.content}`)
        .join('\n\n') +
      (response.verbatimClause
        ? `\n\n${response.verbatimClause.clauseTitle}:\n${response.verbatimClause.excerpt}`
        : '') +
      `\n\nAUTHORITATIVE SOURCES:\n` +
      response.citations
        .map(
          (c) =>
            `[${c.citationNumber}] ${c.title} (${c.circularRef}) - ${c.date}\nVerbatim: ${c.verbatimPassage}`
        )
        .join('\n\n');

    navigator.clipboard.writeText(formattedText).then(() => {
      setCopyFeedback(true);
      setTimeout(() => setCopyFeedback(false), 2000);
    });
  };

  const handleDownloadBrief = () => {
    const formattedText = `========================================================================\n` +
      `REGULENS - SEBI REGULATORY RESEARCH DOSSIER\n` +
      `Securities Law Desk · Desk Edition 2024\n` +
      `========================================================================\n\n` +
      `Timestamp: ${response.timestamp}\n` +
      `Counsel Inquiry: ${response.userQuery}\n\n` +
      `STATUTORY SYNTHESIS:\n` +
      `${response.title}\n` +
      `${response.applicableRegime}\n\n` +
      `------------------------------------------------------------------------\n` +
      `EXECUTIVE SUMMARY:\n` +
      `${response.summaryParagraph}\n\n` +
      `------------------------------------------------------------------------\n` +
      `STATUTORY SUB-CLAUSES & ANALYSIS:\n\n` +
      response.sections
        .map((s) => `${s.title}\n${s.content}`)
        .join('\n\n') +
      (response.verbatimClause
        ? `\n\n------------------------------------------------------------------------\n` +
          `${response.verbatimClause.clauseTitle}\n` +
          `${response.verbatimClause.excerpt}\n`
        : '') +
      `\n------------------------------------------------------------------------\n` +
      `RETRIEVED STATUTORY CORRESPONDENCE & GAZETTE CITATIONS:\n\n` +
      response.citations
        .map(
          (c) =>
            `[${c.citationNumber}] ${c.title}\n` +
            `     Classification: ${c.type}\n` +
            `     Circular Ref: ${c.circularRef}\n` +
            `     Gazette Date: ${c.date}\n` +
            `     Verbatim Extract: ${c.verbatimPassage}\n`
        )
        .join('\n') +
      `\n========================================================================\n` +
      `CONFIDENTIAL ATTORNEY-CLIENT REGULATORY WORK PRODUCT\n` +
      `Generated by ReguLens RAG Engine.\n`;

    const blob = new Blob([formattedText], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `ReguLens_Brief_${response.id || 'SEBI_Memo'}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  // Helper to render text with clickable citation links [1], [2], etc.
  const renderTextWithCitations = (text: string) => {
    const parts = text.split(/(\[\d+\])/g);
    return parts.map((part, index) => {
      const match = part.match(/\[(\d+)\]/);
      if (match) {
        const num = parseInt(match[1], 10);
        return (
          <button
            key={index}
            type="button"
            onClick={() => handleCitationClick(num)}
            title={`Jump to Supporting Evidence [${num}]`}
            className="inline-flex items-center px-1.5 py-0.5 mx-0.5 rounded-[3px] bg-[#eaedff] hover:bg-[#dbe1ff] text-[#00236f] font-semibold text-[11px] border border-[#316bf3]/30 transition-colors cursor-pointer align-baseline select-none"
          >
            [{num}]
          </button>
        );
      }
      return <span key={index}>{part}</span>;
    });
  };

  return (
    <div className="max-w-[800px] mx-auto px-4 sm:px-6 space-y-6">
      {/* 1. User Inquiry Message Card */}
      <div className="flex justify-end">
        <div className="max-w-[92%] sm:max-w-[85%] bg-white border border-[#cbd5e1] rounded-[6px] p-4 shadow-xs">
          <div className="flex items-center justify-between gap-4 mb-2 pb-1.5 border-b border-[#e2e8f0]">
            <span className="text-[11px] font-semibold text-[#444651] flex items-center gap-1 uppercase tracking-wider">
              <span className="material-symbols-outlined text-[14px] text-[#00236f]">person</span>
              Counsel Inquiry
            </span>
            <time className="text-[11px] font-mono text-[#64748b]">
              {response.timestamp}
            </time>
          </div>
          <p className="text-[14px] text-[#131b2e] font-medium leading-relaxed">
            {response.userQuery}
          </p>
        </div>
      </div>

      {/* 2. Official AI Statutory Response (Institutional Legal Brief Style) */}
      <article className="bg-white border border-[#cbd5e1] rounded-[6px] p-5 sm:p-7 shadow-xs space-y-5">
        {/* Regulatory Brief Header */}
        <div className="flex flex-wrap items-center justify-between gap-2 pb-3.5 border-b border-[#e2e8f0]">
          <div className="flex items-center gap-1.5">
            <span className="material-symbols-outlined text-[#00236f] text-[18px]">verified</span>
            <span className="text-[11px] uppercase tracking-wider text-[#00236f] font-bold">
              Official Statutory Synthesis
            </span>
          </div>
          <div className="flex items-center gap-2">
            <span className="inline-flex items-center gap-1 text-[11px] font-mono text-[#444651] bg-[#f2f3ff] px-2 py-0.5 rounded-[3px] border border-[#c5c5d3]/60">
              <span className="w-1.5 h-1.5 rounded-full bg-emerald-600 inline-block"></span>
              {response.confidenceNote}
            </span>
          </div>
        </div>

        {/* Document Title & Subject */}
        <div>
          <h1 className="font-serif-legal text-[22px] sm:text-[24px] font-semibold text-[#00236f] tracking-tight leading-snug">
            {response.title}
          </h1>
          <p className="text-[13px] text-[#64748b] mt-1 leading-normal">
            {response.applicableRegime}
          </p>
        </div>

        {/* Executive Synthesis Body */}
        <div className="space-y-4 text-[#131b2e] text-[14px] leading-relaxed">
          <p className="text-[14px] leading-relaxed">
            {renderTextWithCitations(response.summaryParagraph)}
          </p>

          {/* Numbered Statutory Sections */}
          {response.sections.map((sec, idx) => (
            <div key={idx} className="pt-1">
              <h2 className="font-serif-legal text-[15px] font-semibold text-[#131b2e] mb-1.5 flex items-center gap-1.5">
                <span>{sec.title}</span>
                {sec.citationRefNumber && (
                  <button
                    type="button"
                    onClick={() => handleCitationClick(sec.citationRefNumber!)}
                    className="inline-flex items-center px-1.5 py-0.2 mx-0.5 rounded-[3px] bg-[#eaedff] text-[#00236f] text-[11px] font-semibold border border-[#316bf3]/30 cursor-pointer"
                    title={`View Citation [${sec.citationRefNumber}]`}
                  >
                    [{sec.citationRefNumber}]
                  </button>
                )}
              </h2>
              <p className="text-[14px] text-[#334155] leading-relaxed">
                {renderTextWithCitations(sec.content)}
              </p>
            </div>
          ))}

          {/* Statutory Verbatim Clause Callout */}
          {response.verbatimClause && (
            <blockquote className="my-4 p-4 bg-[#f8f9fa] border-l-4 border-[#00236f] rounded-r-[4px]">
              <div className="flex items-center gap-1.5 text-[#00236f] text-[11px] mb-1 uppercase tracking-wider font-semibold">
                <span className="material-symbols-outlined text-[15px]">menu_book</span>
                {response.verbatimClause.clauseTitle}
              </div>
              <p className="text-[13px] italic font-serif-legal text-[#1e293b] leading-relaxed">
                {response.verbatimClause.excerpt}
              </p>
            </blockquote>
          )}
        </div>

        {/* Action Strip */}
        <div className="pt-4 border-t border-[#e2e8f0] flex flex-wrap items-center justify-between gap-3">
          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handleCopyLegalMemo}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-[4px] bg-[#f8f9fa] hover:bg-[#f1f5f9] border border-[#cbd5e1] text-[#131b2e] text-[12px] font-medium transition-colors cursor-pointer shadow-xs"
            >
              <span className="material-symbols-outlined text-[15px]">
                {copyFeedback ? 'check' : 'content_copy'}
              </span>
              <span>{copyFeedback ? 'Copied to Clipboard' : 'Copy Legal Memo'}</span>
            </button>

            <button
              type="button"
              onClick={handleDownloadBrief}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-[4px] bg-[#f8f9fa] hover:bg-[#f1f5f9] border border-[#cbd5e1] text-[#131b2e] text-[12px] font-medium transition-colors cursor-pointer shadow-xs"
            >
              <span className="material-symbols-outlined text-[15px]">download</span>
              <span>Download Statutory Brief</span>
            </button>
          </div>

          <div className="flex items-center gap-1.5">
            <span className="text-[11px] text-[#00236f] font-semibold flex items-center gap-1">
              <span className="material-symbols-outlined text-[15px]">verified_user</span>
              Verified Against SEBI Gazette Corpus
            </span>
          </div>
        </div>
      </article>

      {/* 3. Collapsible Sources & Supporting Evidence Accordion */}
      {response.citations && response.citations.length > 0 && (
        <div className="bg-white border border-[#cbd5e1] rounded-[6px] overflow-hidden shadow-xs">
          <button
            type="button"
            className="w-full px-5 py-3.5 flex items-center justify-between bg-[#f8f9fa] hover:bg-[#f1f5f9] border-b border-[#e2e8f0] text-left transition-colors cursor-pointer"
            onClick={() => setEvidenceExpanded(!evidenceExpanded)}
          >
            <div className="flex items-center gap-2.5">
              <span className="material-symbols-outlined text-[#00236f] text-[20px]">policy</span>
              <div>
                <span className="font-serif-legal text-[15px] text-[#131b2e] font-semibold block leading-tight">
                  Sources &amp; Supporting Evidence
                </span>
                <span className="text-[11px] text-[#64748b] block mt-0.5">
                  {response.citations.length} Official Regulatory Authorities Retrieved &amp; Cross-Referenced
                </span>
              </div>
            </div>

            <div className="flex items-center gap-2">
              <span className="text-[12px] text-[#00236f] font-semibold hidden sm:inline">
                {evidenceExpanded ? 'Collapse Sources' : `View ${response.citations.length} Primary Sources`}
              </span>
              <span className="material-symbols-outlined text-[#64748b]">
                {evidenceExpanded ? 'expand_less' : 'expand_more'}
              </span>
            </div>
          </button>

          {/* Evidence List */}
          {evidenceExpanded && (
            <div className="p-4 sm:p-5 space-y-4">
              {response.citations.map((source) => {
                const isHighlighted = highlightedSourceId === source.id;
                return (
                  <div
                    key={source.id}
                    id={source.id}
                    className={`border rounded-[6px] p-4 transition-all duration-300 ${
                      isHighlighted
                        ? 'border-[#00236f] bg-[#f2f3ff] ring-2 ring-[#00236f]/30'
                        : 'border-[#cbd5e1] bg-[#ffffff] hover:border-[#94a3b8]'
                    }`}
                  >
                    <div className="flex flex-wrap items-center justify-between gap-2 mb-1.5">
                      <div className="flex items-center gap-2">
                        <span className="inline-block px-1.5 py-0.5 rounded-[3px] bg-[#00236f] text-white text-[11px] font-semibold">
                          Citation [{source.citationNumber}]
                        </span>
                        <span className="inline-block px-2 py-0.5 rounded-[3px] bg-[#eaedff] text-[#00236f] text-[11px] font-semibold border border-[#cbd5e1]">
                          {source.type}
                        </span>
                      </div>
                      <time className="text-[11px] font-mono text-[#64748b]">
                        {source.date}
                      </time>
                    </div>

                    <h3 className="font-serif-legal text-[15px] font-semibold text-[#131b2e] leading-snug">
                      {source.title}
                    </h3>

                    <p className="text-[12px] font-mono text-[#0051d5] mt-0.5 font-medium">
                      Circular Ref: {source.circularRef}
                    </p>

                    {source.department && (
                      <p className="text-[11px] text-[#64748b] mt-0.5">
                        Issuing Wing: {source.department}
                      </p>
                    )}

                    <div className="mt-2.5 p-2.5 bg-[#f8f9fa] border border-[#e2e8f0] rounded-[4px] text-[13px] text-[#334155] leading-relaxed">
                      <span className="font-semibold text-[#00236f]">Verbatim Passage: </span>
                      {source.verbatimPassage}
                    </div>

                    <div className="mt-3 flex justify-end">
                      <a
                        href={source.pdfUrl || '#'}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="inline-flex items-center gap-1 text-[12px] text-[#00236f] hover:text-[#0051d5] font-semibold underline underline-offset-2"
                      >
                        <span>View Official SEBI Circular (Portal ↗)</span>
                      </a>
                    </div>
                  </div>
                );
              })}
            </div>
          )}
        </div>
      )}
    </div>
  );
};
